/**
 * Validates if any component defines a rigid fixed width greater than 375px
 * which would trigger MOD-03 422 ERR_VIEWPORT_OVERFLOW on mobile devices.
 */
export function validateMobileWidthSafety(components: FigCraftComponentNode[]): {
  isSafe: boolean;
  violatingComponents: string[];
} {
  const violating: string[] = [];

  function traverse(node: FigCraftComponentNode) {
    const widthStr = node.layout?.width || '';
    const match = widthStr.match(/^(\d+)px$/);
    if (match) {
      const px = parseInt(match[1], 10);
      if (px > 375 && !node.layout?.maxWidth) {
        violating.push(`${node.name} (${node.id}): fixed width ${widthStr} exceeds 375px mobile threshold`);
      }
    }
    if (node.children) {
      for (const child of node.children) {
        traverse(child);
      }
    }
  }

  for (const comp of components) {
    traverse(comp);
  }

  return {
    isSafe: violating.length === 0,
    violatingComponents: violating,
  };
}

