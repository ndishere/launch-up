/**
 * Generates an architectural SVG diagram string for visual rendering
 * following xflow-lab/figcraft conventions.
 */
export function generateFigCraftSvgDiagram(
  title: string,
  tables: { name: string; columns: string[]; isRls: boolean }[]
): string {
  const nodeWidth = 240;
  const nodeHeight = 160;
  const gapX = 40;
  const startX = 20;
  const startY = 60;

  const totalWidth = Math.max(800, startX + tables.length * (nodeWidth + gapX));
  const totalHeight = 320;

  let svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${totalWidth} ${totalHeight}" width="100%" height="100%" className="w-full h-full select-none">\n`;
  svg += `  <defs>\n`;
  svg += `    <linearGradient id="gridGrad" x1="0%" y1="0%" x2="100%" y2="100%">\n`;
  svg += `      <stop offset="0%" stop-color="#0f172a" />\n`;
  svg += `      <stop offset="100%" stop-color="#020617" />\n`;
  svg += `    </linearGradient>\n`;
  svg += `    <pattern id="smallGrid" width="20" height="20" patternUnits="userSpaceOnUse">\n`;
  svg += `      <path d="M 20 0 L 0 0 0 20" fill="none" stroke="#1e293b" stroke-width="0.5" />\n`;
  svg += `    </pattern>\n`;
  svg += `  </defs>\n`;

  svg += `  <rect width="100%" height="100%" fill="url(#gridGrad)" />\n`;
  svg += `  <rect width="100%" height="100%" fill="url(#smallGrid)" opacity="0.4" />\n`;

  svg += `  <text x="20" y="32" fill="#f8fafc" font-size="16" font-family="monospace" font-weight="bold">FigCraft Architecture Schema: ${title}</text>\n`;

  tables.forEach((t, i) => {
    const x = startX + i * (nodeWidth + gapX);
    const y = startY;

    // Card background
    svg += `  <g transform="translate(${x}, ${y})">\n`;
    svg += `    <rect width="${nodeWidth}" height="${nodeHeight}" rx="8" fill="#0f172a" stroke="#334155" stroke-width="1.5" />\n`;
    svg += `    <rect width="${nodeWidth}" height="32" rx="8" fill="#1e293b" />\n`;
    svg += `    <text x="12" y="20" fill="#38bdf8" font-size="12" font-family="monospace" font-weight="bold">${t.name}</text>\n`;

    if (t.isRls) {
      svg += `    <rect x="${nodeWidth - 58}" y="8" width="48" height="16" rx="4" fill="#065f46" />\n`;
      svg += `    <text x="${nodeWidth - 52}" y="19" fill="#34d399" font-size="9" font-family="sans-serif" font-weight="bold">RLS ON</text>\n`;
    }

    t.columns.slice(0, 4).forEach((col, ci) => {
      svg += `    <text x="12" y="${50 + ci * 20}" fill="#94a3b8" font-size="11" font-family="monospace">• ${col}</text>\n`;
    });

    svg += `  </g>\n`;

    // Connect with arrow if next exists
    if (i < tables.length - 1) {
      const lineStartX = x + nodeWidth;
      const lineStartY = y + 70;
      const lineEndX = lineStartX + gapX;
      svg += `  <line x1="${lineStartX}" y1="${lineStartY}" x2="${lineEndX}" y2="${lineStartY}" stroke="#6366f1" stroke-width="2" stroke-dasharray="4" />\n`;
      svg += `  <polygon points="${lineEndX},${lineStartY} ${lineEndX - 6},${lineStartY - 4} ${lineEndX - 6},${lineStartY + 4}" fill="#6366f1" />\n`;
    }
  });

  svg += `</svg>`;
  return svg;
}
